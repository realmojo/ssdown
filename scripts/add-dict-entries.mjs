for (const tool of TOOLS_NEEDING_DICT_ONLY) {
  const content = readComponent(tool.slug);
  const enStrings = extractAllStrings(content);

  if (!en[tool.dictKey]) {
    en[tool.dictKey] = {};
  }
  // Only add keys that don't already exist
  for (const [key, value] of Object.entries(enStrings)) {
    if (en[tool.dictKey][key] === undefined) {
      en[tool.dictKey][key] = value;
    }
  }

  if (PARTIAL_KR[tool.dictKey]) {
    if (!kr[tool.dictKey]) {
      kr[tool.dictKey] = {};
    }
    // Only add keys that don't already exist
    for (const [key, value] of Object.entries(PARTIAL_KR[tool.dictKey])) {
      if (kr[tool.dictKey][key] === undefined) {
        kr[tool.dictKey][key] = value;
      }
    }
  }

  console.log(`Patched ${tool.dictKey}: EN ${Object.keys(en[tool.dictKey]).length} keys, KR ${Object.keys(kr[tool.dictKey]).length} keys`);
}

