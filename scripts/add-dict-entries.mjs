#!/usr/bin/env node
/**
 * Adds UI dictionary entries for all 44 non-i18n'd tool components
 * to both en.json and kr.json. Also adds missing entries for 3 partially i18n'd tools.
 */

import fs from 'fs';
import path from 'path';

const ROOT = process.cwd();
const EN_PATH = path.join(ROOT, 'dictionaries/en.json');
const KR_PATH = path.join(ROOT, 'dictionaries/kr.json');
const COMPONENTS_DIR = path.join(ROOT, 'components/client');

function readComponent(slug) {
  return fs.readFileSync(path.join(COMPONENTS_DIR, slug + '-client.tsx'), 'utf8');
}

// ============================================================
// Extract English strings from each component
// ============================================================
function extractAllStrings(content) {
  const s = {};

  // h1
  let m = content.match(/<h1[^>]*>\s*\n?\s*([^<{]+?)\s*\n?\s*<\/h1>/);
  if (m) s.title = m[1].trim();

  // subtitle (first p after h1)
  m = content.match(/<\/h1>\s*\n?\s*<p[^>]*>\s*\n?\s*([^<{]+?)\s*\n?\s*<\/p>/);
  if (m) s.subtitle = m[1].trim();

  // Drop zone
  m = content.match(/(Drag & drop[^"<\n]*)/);
  if (!m) m = content.match(/(Drag and drop[^"<\n]*)/);
  if (m) s.drop_zone = m[1].trim();

  // Supported formats
  m = content.match(/(Supported:[^"<\n]*)/);
  if (m) s.supported = m[1].trim();

  // Max file size
  m = content.match(/((?:Recommended )?[Mm]ax (?:file )?size:[^"<\n]*)/);
  if (m) s.max_file_size = m[1].trim();

  // Loading engine
  m = content.match(/(Loading (?:converter |processing )?engine[^"<\n]*)/);
  if (m) s.loading_engine = m[1].trim();

  // Button states - look for specific patterns in button text
  // Action button (the main CTA)
  const btnPatterns = [
    />\s*\n?\s*(Convert to \w[\w ]*)/,
    />\s*\n?\s*(Remove (?:Audio|Background))/,
    />\s*\n?\s*(Trim (?:Video|Audio))/,
    />\s*\n?\s*(Merge PDFs?)\s*\n?\s*</,
    />\s*\n?\s*(Split PDF)\s*\n?\s*</,
    />\s*\n?\s*(Rotate (?:All|PDF))/,
    />\s*\n?\s*(Unlock PDF)/,
    />\s*\n?\s*(Protect PDF)/,
    />\s*\n?\s*(Add Page Numbers)/,
    />\s*\n?\s*(Rearrange Pages)/,
    />\s*\n?\s*(Extract Frames)/,
    />\s*\n?\s*(Mute Video)/,
    />\s*\n?\s*(Crop Image)/,
    />\s*\n?\s*(Flip (?:Horizontal|Image))/,
    />\s*\n?\s*(Apply (?:Pixelation|Blur|Effect))/,
    />\s*\n?\s*(Create PDF)/,
    />\s*\n?\s*(Sign PDF)/,
    />\s*\n?\s*(Add Watermark)/,
    />\s*\n?\s*(Generate (?:Favicon|Collage|Thumbnails?))/,
    />\s*\n?\s*(Compress Image)/,
    />\s*\n?\s*(Download (?:Excel|CSV|XML|JSON|PDF))\s*\n?\s*</,
  ];
  for (const pat of btnPatterns) {
    m = content.match(pat);
    if (m) { s.action_btn = m[1].trim(); break; }
  }

  // Processing text
  const procPatterns = [
    /(Converting\.\.\.)/,
    /(Processing\.\.\.)/,
    /(Removing audio\.\.\.)/,
    /(Trimming\.\.\.)/,
    /(Merging\.\.\.)/,
    /(Splitting\.\.\.)/,
    /(Rotating\.\.\.)/,
    /(Extracting\.\.\.)/,
    /(Compressing\.\.\.)/,
    /(Generating\.\.\.)/,
    /(Unlocking\.\.\.)/,
    /(Protecting\.\.\.)/,
    /(Cropping\.\.\.)/,
    /(Applying\.\.\.)/,
    /(Muting\.\.\.)/,
  ];
  for (const pat of procPatterns) {
    m = content.match(pat);
    if (m) { s.processing = m[1].trim(); break; }
  }

  // Success message
  const successPatterns = [
    /(Conversion Complete!)/,
    /(Audio Removed Successfully!)/,
    /(Trim Complete!)/,
    /(Processing Complete!)/,
    /(Merge Complete!)/,
    /(Split Complete!)/,
    /(Rotation Complete!)/,
    /(Unlock Complete!)/,
    /(Protection (?:Applied|Complete)!)/,
    /(Page Numbers Added!)/,
    /(Pages Rearranged!)/,
    /(Extraction Complete!)/,
    /(Frames Extracted!)/,
    /(Download Ready!)/,
    /(Crop Complete!)/,
    /(Image (?:Flipped|Pixelated|Blurred|Cropped)!)/,
    /(Collage Created!)/,
    /(PDF Created!)/,
    /(Watermark Added!)/,
    /(\w[\w ]+Complete!)/,
    /(\w[\w ]+Successfully!)/,
    /(\w[\w ]+ Ready!)/,
  ];
  for (const pat of successPatterns) {
    m = content.match(pat);
    if (m) { s.success_msg = m[1].trim(); break; }
  }

  // Download button
  m = content.match(/(Download [\w& ]+?)(?:\s*\n|\s*<)/);
  if (m) s.download_btn = m[1].trim();

  // "Another" button
  const anotherPatterns = [
    /(Convert Another[\w ]*)/,
    /(Mute Another[\w ]*)/,
    /(Trim Another[\w ]*)/,
    /(Merge Another[\w ]*)/,
    /(Process Another[\w ]*)/,
    /(Extract Another[\w ]*)/,
    /(Upload Another[\w ]*)/,
    /(Try Another[\w ]*)/,
    /(Crop Another[\w ]*)/,
    /(Start Over)/,
    /(Reset)/,
  ];
  for (const pat of anotherPatterns) {
    m = content.match(pat);
    if (m) { s.another_btn = m[1].trim(); break; }
  }

  // How-to guide title
  m = content.match(/<h2[^>]*>\s*\n?\s*(How to [^<]+?)\s*\n?\s*<\/h2>/);
  if (m) s.guide_title = m[1].trim();

  // How-to guide description
  m = content.match(/How to[\s\S]*?<\/h2>\s*\n?\s*<p[^>]*>\s*\n?\s*([^<{]+?)\s*\n?\s*<\/p>/);
  if (m) s.guide_desc = m[1].trim();

  // Steps (from array objects)
  const stepPattern = /step:\s*(\d+),\s*\n?\s*title:\s*"([^"]+)",\s*\n?\s*desc:\s*"([^"]+)"/g;
  let stepMatch;
  while ((stepMatch = stepPattern.exec(content)) !== null) {
    s[`step${stepMatch[1]}_title`] = stepMatch[2];
    s[`step${stepMatch[1]}_desc`] = stepMatch[3];
  }

  // Tips section title
  m = content.match(/<h2[^>]*>\s*\n?\s*([^<]*?(?:Tips|Best Practices)[^<]*?)\s*\n?\s*<\/h2>/);
  if (m) s.tips_title = m[1].trim();

  // Tips description
  m = content.match(/(?:Tips|Best Practices)[\s\S]*?<\/h2>\s*\n?\s*<p[^>]*>\s*\n?\s*([^<{]+?)\s*\n?\s*<\/p>/);
  if (m) s.tips_desc = m[1].trim();

  // Tip items - these come AFTER the step items in the file
  // We need to find the tips array which is in the second array after the guide section
  const tipsArrayMatch = content.match(/(?:Tips|Best Practices)[\s\S]*?\[\s*\n([\s\S]*?)\]\.map/);
  if (tipsArrayMatch) {
    const tipsBlock = tipsArrayMatch[1];
    const tipItemPattern = /title:\s*"([^"]+)",\s*\n?\s*desc:\s*"([^"]+)"/g;
    let tipMatch;
    let tipIdx = 1;
    while ((tipMatch = tipItemPattern.exec(tipsBlock)) !== null) {
      s[`tip${tipIdx}_title`] = tipMatch[1];
      s[`tip${tipIdx}_desc`] = tipMatch[2];
      tipIdx++;
    }
  }

  // FAQ section title
  m = content.match(/<h2[^>]*>\s*\n?\s*([^<]*?FAQ[^<]*?)\s*\n?\s*<\/h2>/);
  if (m) s.faq_title = m[1].trim();

  // FAQ description
  m = content.match(/FAQ[\s\S]*?<\/h2>\s*\n?\s*<p[^>]*>\s*\n?\s*([^<{]+?)\s*\n?\s*<\/p>/);
  if (m) s.faq_desc = m[1].trim();

  // FAQ Q&A items
  const faqQPattern = /<AccordionTrigger[^>]*>\s*\n?\s*([^<{]+?)\s*\n?\s*<\/AccordionTrigger>/g;
  const faqAPattern = /<AccordionContent[^>]*>\s*\n?\s*([^<{]+?)\s*\n?\s*<\/AccordionContent>/g;
  let faqQ, faqA;
  let faqIdx = 1;
  while ((faqQ = faqQPattern.exec(content)) !== null) {
    s[`faq_${faqIdx}_q`] = faqQ[1].trim();
    faqIdx++;
  }
  faqIdx = 1;
  while ((faqA = faqAPattern.exec(content)) !== null) {
    s[`faq_${faqIdx}_a`] = faqA[1].trim();
    faqIdx++;
  }

  return s;
}

